function service_url(string $slug): string
{
    return app_url('service/' . rawurlencode($slug));
}

function service_start_url(string $slug): string
{
    return app_url();
}

function find_service(string $slug): ?array
{
    if ($slug === '') {
        return null;
    }

    $services = services_catalog();
    return $services[$slug] ?? null;
}

function service_plain_description(array $blocks): string
{
    $parts = [];

    foreach ($blocks as $block) {
        if (isset($block['p']) && is_string($block['p'])) {
            $parts[] = $block['p'];
        }
        if (isset($block['items']) && is_array($block['items'])) {
            foreach ($block['items'] as $item) {
                $parts[] = (string) $item;
            }
        }
        if (isset($block['defs']) && is_array($block['defs'])) {
            foreach ($block['defs'] as $def) {
                $label = (string) ($def['label'] ?? '');
                $text = (string) ($def['text'] ?? '');
                $parts[] = trim($label . ': ' . $text);
            }
        }
    }

    return implode(' ', $parts);
}

function service_inline_html(string $text): string
{
    $escaped = e($text);
    $portal = e(app_url('portal'));

    return (string) preg_replace(
        '/اضغط هنا/',
        '<a class="ServiceDescriptionAccordion__link" href="' . $portal . '">اضغط هنا</a>',
        $escaped
    );
}

function service_description_html(array $blocks): string
{
    if ($blocks === []) {
        return '';
    }

    $html = '';

    foreach ($blocks as $block) {
        if (isset($block['p']) && is_string($block['p'])) {
            $html .= '<p class="ServiceDescriptionAccordion__p">' . service_inline_html($block['p']) . '</p>';
        }

        if (isset($block['items']) && is_array($block['items'])) {
            $html .= '<ul class="ServiceDescriptionAccordion__list">';
            foreach ($block['items'] as $item) {
                $html .= '<li>' . e((string) $item) . '</li>';
            }
            $html .= '</ul>';
        }

        if (isset($block['defs']) && is_array($block['defs'])) {
            foreach ($block['defs'] as $def) {
                $label = (string) ($def['label'] ?? '');
                $text = (string) ($def['text'] ?? '');
                $html .= '<p class="ServiceDescriptionAccordion__p ServiceDescriptionAccordion__p--def"><strong>' . e($label) . ':</strong> ' . e($text) . '</p>';
            }
        }
    }

    return $html;
}
